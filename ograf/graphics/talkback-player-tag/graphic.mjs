/**
 * Talkback player tag: a name tag anchored to a point on the picture, with optional speed and distance.
 * x and y are fractions of the frame, so the tag can follow a player on the pitch render.
 * OGraf v1 graphic: https://ograf.ebu.io/v1/specification/docs/Specification.html
 */

