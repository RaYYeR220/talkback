function settle(el, maxMs = 2500) {
  void el.offsetWidth;
  const running = el.getAnimations({ subtree: true })
    .filter((a) => a.effect?.getComputedTiming?.().iterations !== Infinity)
    .map((a) => a.finished.catch(() => undefined));
  return Promise.race([Promise.all(running), new Promise((ok) => setTimeout(ok, maxMs))]);
}

function text(v) {
  return v === undefined || v === null ? "" : String(v);
}

function fmt(v, decimals = 0) {
  const n = Number(v);
  return Number.isFinite(n) ? n.toFixed(Math.max(0, Math.min(3, decimals | 0))) : "";
}

function clamp01(v) {
  const n = Number(v);
  return Number.isFinite(n) ? Math.min(1, Math.max(0, n)) : 0;
}

class TalkbackGraphic extends HTMLElement {
  static stepCount = 1;
  static defaults = {};

  constructor() {
    super();
    this._shadow = this.attachShadow({ mode: "open" });
    this._data = {};
    this._step = undefined;
    this._root = null;
    this._resize = null;
  }

  async load({ data, renderType = "realtime", renderCharacteristics } = {}) {
    if (renderType !== "realtime") {
      return { statusCode: 400, statusMessage: "Only real-time rendering is supported" };
    }
    this._data = { ...this.constructor.defaults, ...(data && typeof data === "object" ? data : {}) };
    this._step = undefined;
    this._shadow.innerHTML = `<style>${BASE_CSS}${this.css()}</style><div class="frame">${this.markup()}</div>`;
    this._frame = this._shadow.querySelector(".frame");
    this._root = this._shadow.querySelector(".root");
    this._fit(renderCharacteristics);
    this._resize = new ResizeObserver(() => this._fit());
    this._resize.observe(this);
    await this._apply(true, {});
    return { statusCode: 200 };
  }

  async dispose() {
    this._resize?.disconnect();
    this.teardown();
    this._shadow.innerHTML = "";
    this._root = null;
    return { statusCode: 200 };
  }

  async updateAction({ data, skipAnimation = false } = {}) {
    const prev = this._data;
    this._data = { ...this._data, ...(data && typeof data === "object" ? data : {}) };
    await this._apply(skipAnimation, prev);
    return { statusCode: 200 };
  }

  async playAction({ goto, delta, skipAnimation = false } = {}) {
    const target = this._targetStep({ goto, delta });
    if (target === undefined) {
      await this._transition(false, skipAnimation);
      this._step = undefined;
      this.onStop();
      return { statusCode: 200, currentStep: undefined };
    }
    this._step = target;
    this.onPlay(skipAnimation);
    await this._transition(true, skipAnimation);
    return { statusCode: 200, currentStep: this._step };
  }

  async stopAction({ skipAnimation = false } = {}) {
    this._step = undefined;
    this.onStop();
    await this._transition(false, skipAnimation);
    return { statusCode: 200 };
  }

  async customAction({ id, payload, skipAnimation = false } = {}) {
    return this.custom(id, payload ?? {}, skipAnimation);
  }

  _targetStep({ goto, delta } = {}) {
    const count = this.constructor.stepCount;
    const target = Number.isInteger(goto) && goto >= 0
      ? goto
      : (this._step ?? -1) + (Number.isFinite(delta) ? Math.trunc(delta) : 1);
    if (count === 0 || (count > 0 && target >= count)) return undefined;
    return Math.max(0, target);
  }

  _fit(rc) {
    if (!this._frame) return;
    const w = this.clientWidth || rc?.resolution?.width || FRAME_W;
    const h = this.clientHeight || rc?.resolution?.height || FRAME_H;
    this._frame.style.setProperty("--_scale", String(Math.min(w / FRAME_W, h / FRAME_H)));
  }

  async _apply(skip, prev) {
    if (!this._root) return;
    const d = this._data;
    this._root.dir = d.dir === "rtl" ? "rtl" : "ltr";
    if (d.lang) this._root.lang = String(d.lang);
    else this._root.removeAttribute("lang");
    if (skip) this._root.classList.add("cut");
    this.render(d, prev, skip);
    if (skip) {
      void this._root.offsetWidth;
      this._root.classList.remove("cut");
    } else if (this._step !== undefined) {
      await settle(this._root);
    }
  }

  async _transition(on, skip) {
    const root = this._root;
    if (!root) return;
    if (skip) {
      root.classList.add("cut");
      root.classList.toggle("on", on);
      void root.offsetWidth;
      root.classList.remove("cut");
      return;
    }
    root.classList.toggle("on", on);
    await settle(root);
  }

  $(name) {
    return this._shadow.querySelector(`[data-f="${name}"]`);
  }

  setText(name, value, { hideEmpty = false } = {}) {
    for (const el of this._shadow.querySelectorAll(`[data-f="${name}"]`)) {
      el.textContent = text(value);
      if (hideEmpty) el.hidden = text(value) === "";
    }
  }

  css() { return ""; }
  markup() { return `<div class="root"></div>`; }
  render(_data, _prev, _skip) {}
  onPlay(_skip) {}
  onStop() {}
  teardown() {}
  custom(id) { return { statusCode: 400, statusMessage: `Unknown custom action: ${text(id)}` }; }
}
// ---- end talkback ograf base ----

function measure(v, unit, decimals) {
  const n = Number(v);
  return v === undefined || v === null || !Number.isFinite(n) || n < 0 ? "" : `${fmt(n, decimals)} ${text(unit)}`;
}

export default class TalkbackPlayerTag extends TalkbackGraphic {
  static defaults = { name: "", number: "", club: "", clubColor: "", speedUnit: "km/h", distanceUnit: "km", x: 0.5, y: 0.6 };

  css() {
    return `
.tag { left: calc(var(--x, 0.5) * ${FRAME_W}px); top: calc(var(--y, 0.6) * ${FRAME_H}px); }
.root.tag.on { transition: opacity var(--_in) var(--_ease), transform var(--_in) var(--_ease), left 160ms linear, top 160ms linear; }
.pos { position: absolute; left: 0; bottom: 0; transform: translateX(-50%); display: flex; flex-direction: column; align-items: center; }
.box { display: flex; flex-direction: column; align-items: center; padding: 8px 14px 9px; white-space: nowrap; }
.top { display: flex; align-items: center; gap: 10px; font-size: 22px; font-weight: 700; }
.no { min-width: 32px; padding: 1px 6px; text-align: center; font-size: 18px; font-weight: 800; color: var(--_on-accent); background: var(--c, var(--_accent)); border-radius: var(--_radius); }
.club { font-size: 15px; font-weight: 750; color: var(--_muted); }
.stats { display: flex; gap: 8px; margin-top: 3px; font-size: 16px; font-weight: 550; color: var(--_muted); }
.stem { width: 1px; height: 26px; background: var(--_hairline); }
.pin { width: 8px; height: 8px; margin-bottom: -4px; border-radius: 50%; background: var(--_accent); box-shadow: 0 0 0 3px rgba(0, 0, 0, 0.35); }
`;
  }

  markup() {
    return `
<div class="root tag">
  <div class="pos">
    <div class="box plate">
      <div class="top"><span class="no num" data-f="number"></span><span data-f="name"></span><span class="club caps" data-f="club"></span></div>
      <div class="stats num" data-f="stats"><span data-f="speedText"></span><span data-f="dot">·</span><span data-f="distanceText"></span></div>
    </div>
    <div class="stem"></div>
    <div class="pin"></div>
  </div>
</div>`;
  }

  render(d) {
    this.setText("number", d.number, { hideEmpty: true });
    this.setText("name", d.name);
    this.setText("club", d.club, { hideEmpty: true });
    const speed = measure(d.speed, d.speedUnit, 1);
    const distance = measure(d.distance, d.distanceUnit, 1);
    this.setText("speedText", speed, { hideEmpty: true });
    this.setText("distanceText", distance, { hideEmpty: true });
    this.$("dot").hidden = !(speed && distance);
    this.$("stats").hidden = !(speed || distance);
    this._root.style.setProperty("--x", String(clamp01(d.x)));
    this._root.style.setProperty("--y", String(clamp01(d.y)));
    this.$("number").style.setProperty("--c", text(d.clubColor) || "var(--_accent)");
  }
}
